"""Расчёт цены и курьерской доли.

Правило цены: первый пакет 150₽, дальше +60₽.
1→150, 2→210, 3→270, 4→330.

Курьерская доля (что отдаём курьеру за заказ):
1→60, 2→85, 3→110, 4→135.
"""

PRICES = {1: 150, 2: 210, 3: 270, 4: 330}
COURIER_PAY = {1: 60, 2: 85, 3: 110, 4: 135}
MAX_BAGS = 4


def calculate_price(bags: int) -> int:
    return PRICES.get(bags, 0)


def calculate_courier_pay(bags: int) -> int:
    return COURIER_PAY.get(bags, 0)



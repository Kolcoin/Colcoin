"""Расчёт цены.

Правило: первый пакет — 150₽, каждый следующий +60₽.
1 → 150, 2 → 210, 3 → 270.
"""


def calculate_price(bags: int) -> int:
    if bags < 1:
        return 0
    return 150 + 60 * (bags - 1)



def build_csv():
    """
    Формат файла для импорта в Директ (Excel-шаблон):
    https://yandex.ru/support/direct/efficiency/csv-import.html

    Колонки соответствуют столбцам в Excel-шаблоне Yandex.Direct.
    Загружается через интерфейс: Кампании → Импорт из XLS/XLSX.

    ВАЖНО: финальная загрузка делается через Excel-шаблон Директа.
    Этот CSV — это исходные данные, которые удобно перенести вручную
    или конвертировать в .xls макрос-инструментом Direct Commander.
    """
    rows = []
    rows.append([
        "Группа", "Тип объявления",
        "Заголовок 1", "Заголовок 2", "Заголовок 3",
        "Текст", "Отображаемая ссылка", "Ссылка",
        "Регион", "Ключевые фразы", "Минус-слова",
    ])

    for grp in GROUPS:
        utm = UTM.format(group=grp["id"])
        landing_full = SITE + grp["landing"] + utm
        kw_block = "\n".join("+" + " +".join(kw.split()) for kw in grp["keywords"])

        for i, ad in enumerate(grp["ads"]):
            rows.append([
                grp["name"],
                "Текстово-графическое",
                ad["title1"], ad["title2"], ad["title3"],
                ad["text"],
                ad["display"],
                landing_full,
                "Мытищи, Мытищинский городской округ",
                kw_block if i == 0 else "",  # ключи указываются на первой строке группы
                "\n".join(MINUS_WORDS) if (grp == GROUPS[0] and i == 0) else "",
            ])

    out_csv = ROOT / "mytishchi_directs.csv"
    with open(out_csv, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f, delimiter=";")
        for r in rows:
            w.writerow(r)
    return out_csv


def build_keywords_txt():
    """Все ключевые слова одним списком (для прогноза бюджета в Директе)."""
    lines = []
    for grp in GROUPS:
        lines.append(f"# === {grp['name']} ===")
        for kw in grp["keywords"]:
            lines.append(kw)
        lines.append("")
    out = ROOT / "mytishchi_keywords.txt"
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def build_minus_txt():
    out = ROOT / "mytishchi_minus.txt"
    out.write_text("\n".join(MINUS_WORDS), encoding="utf-8")
    return out


def build_summary():
    """Человекочитаемое резюме."""
    lines = [
        f"# Структура кампании в Яндекс.Директ — {CITY}",
        "",
        f"**Сайт:** {SITE}",
        f"**Регион показа:** Мытищи, Мытищинский городской округ",
        f"**Метрика:** 109160037 (счётчик уже стоит на сайте)",
        "",
        "## Группы объявлений",
        "",
    ]
    total_kw = 0
    total_ads = 0
    for grp in GROUPS:
        utm = UTM.format(group=grp["id"])
        lines.append(f"### {grp['name']}")
        lines.append(f"- **Посадочная:** `{SITE}{grp['landing']}{utm}`")
        lines.append(f"- **Ключевых фраз:** {len(grp['keywords'])}")
        lines.append(f"- **Объявлений в группе:** {len(grp['ads'])} (А/Б/В тест)")
        lines.append("")
        lines.append("**Ключевые фразы:**")
        lines.append("```")
        for kw in grp["keywords"]:
            lines.append("+" + " +".join(kw.split()))
        lines.append("```")
        lines.append("")
        lines.append("**Объявления:**")
        lines.append("")
        for i, ad in enumerate(grp["ads"], 1):
            lines.append(f"**Объявление {chr(64+i)}**")
            lines.append(f"- Заголовок 1: `{ad['title1']}`")
            lines.append(f"- Заголовок 2: `{ad['title2']}`")
            lines.append(f"- Заголовок 3: `{ad['title3']}`")
            lines.append(f"- Текст: {ad['text']}")
            lines.append(f"- Отображаемая ссылка: `{ad['display']}`")
            lines.append("")
        total_kw += len(grp["keywords"])
        total_ads += len(grp["ads"])

    lines.extend([
        "## Минус-слова (общие для всей кампании)",
        "",
        "```",
        "\n".join(MINUS_WORDS),
        "```",
        "",
        "## UTM-метки",
        "",
        "На каждой посадочной автоматически прокидываются параметры визита в Метрику:",
        "- `utm_source=yandex`",
        "- `utm_medium=cpc`",
        f"- `utm_campaign=mytishchi_search`",
        "- `utm_content={group_id}` (g1_pokhorony / g2_agent / g3_kremaciya / g4_morg)",
        "- `utm_term={keyword}` (подставляется Директом)",
        "",
        f"## Итого: {len(GROUPS)} групп, {total_kw} ключевых фраз, {total_ads} объявлений",
    ])
    out = ROOT / "mytishchi_summary.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    return out



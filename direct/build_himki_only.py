def empty_row():
    return [""] * 66


def main():
    wb = Workbook()
    ws = wb.active
    ws.title = "Тексты"

    # Первые 9 строк — пустая шапка (как в шаблоне Яндекса)
    for _ in range(9):
        ws.append([""] * 66)

    # Строка 10: заголовки 66 колонок
    headers = [h if h is not None else "" for h in HEADERS]
    ws.append(headers)

    # Стилизация заголовков
    header_row = ws[10]
    fill = PatternFill(start_color="6E2A2A", end_color="6E2A2A", fill_type="solid")
    font = Font(color="FFFFFF", bold=True, size=10)
    align = Alignment(horizontal="center", vertical="center", wrap_text=True)
    for cell in header_row:
        if cell.value:
            cell.fill = fill
            cell.font = font
            cell.alignment = align
    ws.row_dimensions[10].height = 32

    minus_str = " ".join("-" + w for w in MINUS_WORDS)
    clarify_str = "||".join(CLARIFICATIONS)
    ql_titles = "||".join(QUICK_LINKS_TITLES)
    ql_descrs = "||".join(QUICK_LINKS_DESCRIPTIONS)
    ql_urls = "||".join(QUICK_LINKS_URLS)

    # Данные начинаются со строки 11
    for grp in GROUPS:
        for ad_idx, ad in enumerate(grp["ads"]):
            for kw_idx, kw in enumerate(grp["keywords"]):
                row = empty_row()

                # "Доп" — для дополнительных объявлений в группе
                is_extra_ad = ad_idx > 0 and kw_idx == 0
                row[0] = "Доп" if is_extra_ad else "-"
                row[1] = "Текстово-графическое"

                # Имя группы — только на первой строке группы
                if ad_idx == 0 and kw_idx == 0:
                    row[3] = grp["name"]
                    row[4] = grp["num"]
                    row[48] = "Химки"  # Регион
                    row[64] = minus_str  # Минус-фразы

                # Фраза — заполняется только для первого объявления каждой группы
                if ad_idx == 0:
                    row[6] = kw

                # Объявление заполняется при kw_idx == 0 для каждого ad_idx
                if kw_idx == 0:
                    row[8] = ad["h1"][:56]
                    row[9] = ad["h2"][:30]
                    row[10] = ad["text"][:81]
                    row[46] = grp["landing"]
                    row[47] = grp["display_path"][:20]
                    row[50] = 300  # Максимальная ставка 300 ₽ (как обсуждали)
                    row[51] = 0
                    row[54] = ql_titles
                    row[55] = ql_descrs
                    row[56] = ql_urls
                    row[63] = clarify_str

                ws.append(row)

    # Ширина колонок
    widths = {
        1: 14, 2: 22, 4: 28, 5: 12, 7: 12, 8: 35,
        9: 14, 10: 30, 11: 42, 47: 50, 48: 22, 49: 18,
        50: 20, 51: 11, 52: 11, 55: 28, 56: 28, 57: 28,
        58: 14, 59: 14, 60: 20, 64: 25, 65: 25,
    }
    from openpyxl.utils import get_column_letter
    for col_idx, w in widths.items():
        ws.column_dimensions[get_column_letter(col_idx)].width = w

    out_path = OUT / "campaign_himki_v2.xlsx"
    wb.save(out_path)
    print(f"✅ Сохранено: {out_path}")
    print(f"   {len(GROUPS)} групп")
    total_kw = sum(len(g['keywords']) for g in GROUPS)
    total_ads = sum(len(g['ads']) for g in GROUPS)
    print(f"   {total_kw} ключей всего")
    print(f"   {total_ads} объявлений всего")


if __name__ == "__main__":
    main()
